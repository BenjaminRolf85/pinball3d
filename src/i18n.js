let lang = 'de';
let table = 'riff';
const subs = [];

export function setTable(id) { table = tableDict[id] || id === 'riff' ? id : 'riff'; }
export function getTable() { return table; }

export function setLang(l) {
  lang = dict[l] ? l : 'de';
  for (const fn of subs) fn(lang);
}
export function getLang() { return lang; }
export function onLang(fn) { subs.push(fn); }

export function fmtNum(n) {
  const s = String(Math.max(0, Math.round(n)));
  return s.replace(/\B(?=(\d{3})+(?!\d))/g, lang === 'de' ? '.' : ',');
}

function fill(str, vars) {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (_, k) => {
    const v = vars[k];
    if (v === undefined) return '';
    return k === 'p' ? fmtNum(v) : String(v);
  });
}

/** Translate. Arrays are returned as arrays with variables filled in. */
export function t(key, vars) {
  const td = tableDict[table];
  const v = td?.[lang]?.[key] ?? td?.de?.[key] ?? dict[lang][key] ?? dict.de[key] ?? key;
  if (Array.isArray(v)) return v.map((x) => (typeof x === 'string' ? fill(x, vars) : x));
  return fill(v, vars);
}
